# ---------------------------------------------------------------------------
# Cached helpers
# ---------------------------------------------------------------------------
@st.cache_data(show_spinner="Loading and cleaning data...")
def load_data(uploaded_bytes):
    """Load the bundled sample (uploaded_bytes is None) or an uploaded CSV."""
    if uploaded_bytes is None:
        if not SAMPLE_PATH.exists():  # regenerate the synthetic sample if it was deleted
            dp.save_synthetic_csv(SAMPLE_PATH)
        raw = dp.load_csv(SAMPLE_PATH)
    else:
        raw = dp.load_csv(io.BytesIO(uploaded_bytes))
    return dp.clean_data(raw)


@st.cache_resource(show_spinner="Training the PM2.5 model (a few seconds)...")
def train_model(df: pd.DataFrame):
    """Train and evaluate the model. Returns (result, error_message)."""
    try:
        return pr.train_and_evaluate(df), None
    except pr.InsufficientDataError as exc:
        return None, str(exc)


