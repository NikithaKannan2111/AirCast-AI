# ---------------------------------------------------------------------------
with tabs[6]:
    st.subheader("Model performance")
    if result is None:
        st.warning(f"No model was trained. {model_error}")
    else:
        st.dataframe(pr.metrics_table(result))
        st.markdown(f"**Verdict:** {pr.describe_performance(result)}")
        st.caption(
            f"Training rows: {result.n_train:,} | Test rows: {result.n_test:,} | "
            f"Chronological split at {result.test_start:%Y-%m-%d}."
        )
        top = result.feature_importance.head(10).sort_values("importance")
        imp = px.bar(top, x="importance", y="feature", orientation="h", title="Top 10 feature importances")
        st.plotly_chart(imp)

    st.subheader("Methodology")
    st.markdown(
        """
        - **Target:** daily mean PM2.5 of one location.
        - **Features:** PM2.5 of the previous 1, 2, 3 and 7 days, mean of the previous 7 days,
          previous-day PM10/NO2/O3/temperature/humidity/wind, calendar features and the location.
        - **No leakage:** every feature is shifted so it only uses earlier days; imputation and
          encoding are fitted on the training rows only.
        - **Evaluation:** earliest ~80 % of dates train the model, latest ~20 % are held out.
        - **Baseline:** "same as yesterday" - a model is only useful if it beats this.
        """
    )

    st.subheader("Limitations")
    st.markdown(
        """
        - The bundled dataset is **synthetic**, so the metrics describe the simulation, **not** real air quality.
        - The model forecasts only **one day ahead** and relies heavily on yesterday's PM2.5.
        - It does not know about future weather, traffic, fires, festivals or industrial events.
        - Results from one chronological test window may not hold in other seasons or years.
        - Missing values are median-imputed, which can hide real patterns.
        - Alert categories are educational and are not medical or regulatory advice.
        """
    )
