# 4. PM2.5 prediction
# ---------------------------------------------------------------------------
# The model is trained on ALL cleaned data (not the sidebar filter) so results
# do not change when you move the date slider.
result, model_error = train_model(data)

with tabs[3]:
    st.subheader("PM2.5 prediction (next-day forecast & held-out test)")
    if result is None:
        st.warning(f"A model could not be trained with this dataset. {model_error}")
    else:
        st.markdown(
            f"A Random Forest model predicts **daily mean PM2.5** from past information only "
            f"(previous days' PM2.5, previous-day weather/other pollutants, calendar features). "
            f"It was trained on dates up to **{result.train_end:%Y-%m-%d}** and tested on "
            f"**{result.test_start:%Y-%m-%d}** onward - data it never saw during training."
        )
        mm, bm = result.metrics["model"], result.metrics["baseline"]
        k1, k2, k3 = st.columns(3)
        k1.metric("MAE (test)", f"{mm['MAE']:.2f}", delta=f"{mm['MAE'] - bm['MAE']:+.2f} vs baseline", delta_color="inverse")
        k2.metric("RMSE (test)", f"{mm['RMSE']:.2f}", delta=f"{mm['RMSE'] - bm['RMSE']:+.2f} vs baseline", delta_color="inverse")
        k3.metric("R2 (test)", f"{mm['R2']:.3f}", delta=f"{mm['R2'] - bm['R2']:+.3f} vs baseline")
        st.caption("Baseline = predict 'same as yesterday'. Negative MAE/RMSE deltas mean the model is better.")

        tested = set(result.test_predictions["location"])
        test_locs = [loc for loc in selected_locations if loc in tested]
        if not test_locs:
            st.info("The selected locations have no held-out test data.")
        else:
            chosen = st.selectbox("Location", test_locs, key="pred_loc")
            sub = result.test_predictions[result.test_predictions["location"] == chosen].sort_values("date")
            forecast = pr.forecast_next_day(data, result)
            f_row = forecast[forecast["location"] == chosen]

            fig = go.Figure()
            fig.add_trace(go.Scatter(x=sub["date"], y=sub["actual_pm25"], mode="lines",
                                     name="Actual (observed)", line=dict(width=2)))
            fig.add_trace(go.Scatter(x=sub["date"], y=sub["predicted_pm25"], mode="lines",
                                     name="Model prediction", line=dict(width=2, dash="dash")))
            if not f_row.empty:
                fig.add_trace(go.Scatter(x=f_row["forecast_date"], y=f_row["predicted_pm25"], mode="markers",
                                         name="Next-day FORECAST (not observed)",
                                         marker=dict(size=13, symbol="star")))
            fig.update_layout(
                title=f"{chosen}: actual vs predicted PM2.5 on held-out dates",
                xaxis_title="Date", yaxis_title="PM2.5 (ug/m3)", hovermode="x unified",
            )
            st.plotly_chart(fig)

            loc_mae = sub["abs_error"].mean()
            st.caption(f"Mean absolute error for {chosen} on the test period: {loc_mae:.2f} ug/m3.")

        st.markdown("#### Next-day forecasts (predictions, not observations)")
        forecast_all = pr.forecast_next_day(data, result)
        forecast_all = forecast_all[forecast_all["location"].isin(selected_locations)]
        if forecast_all.empty:
            st.info("No forecast could be produced (the latest day has no previous-day PM2.5 value).")
        else:
            show = forecast_all.copy()
            show["forecast_date"] = pd.to_datetime(show["forecast_date"]).dt.strftime("%Y-%m-%d")
            show = show.rename(columns={"predicted_pm25": "Predicted PM2.5 (ug/m3)", "alert_level": "Predicted category"})
            st.dataframe(show, hide_index=True)

        with st.expander("Show held-out predictions vs actual values"):
            table = result.test_predictions[result.test_predictions["location"].isin(selected_locations)].copy()
            table["date"] = pd.to_datetime(table["date"]).dt.strftime("%Y-%m-%d")
            st.dataframe(table.round(2), hide_index=True)

